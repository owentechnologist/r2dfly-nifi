#!/usr/bin/env bash
# Times r2dfly and RedisShake moving the same dataset between the same two containers on this
# machine, so the comparison in docs/r2dfly-vs-redisshake.md can be rerun. Scratch containers
# only: it creates its own source, target and network and removes them afterwards.
set -euo pipefail

PROJECT_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"

usage() {
  cat <<EOF
Usage: $(basename "$0") --dataset strings|hashes|lists|live [options]

Datasets:
  strings   --keys small strings (64-byte values)                        default --keys 10000000
  hashes    --keys hashes of 20 fields, 32-byte values                   default --keys 1000000
  lists     --keys lists of 1000 elements, 100-byte values               default --keys 10000
  live      100k strings copied first, then 60 s of redis-benchmark writes (SET, INCR, HSET,
            LPUSH on 1M random keys) during the live sync; reports how long after the writes
            stop the target takes to hold every key with the source's values

Each bulk dataset is timed from the first key reaching the target until all of them have: tool
start-up (NiFi deploy, container start) is left out on both sides. RedisShake runs its default
replication reader (sync_reader) and, with --shake-scan, its scan reader as well. r2dfly runs
simple-migration.sh (bulk) or continuous-migration.sh --live-source replication (live).

Options:
  --keys N                 dataset size (defaults above)
  --nifi-container NAME    NiFi container r2dfly deploys to (default: r2dfly-bench-nifi; created
                           if missing, and left running for the next dataset)
  --shake-scan             also time RedisShake's scan_reader
  --skip-redisshake        r2dfly only
  --skip-r2dfly            RedisShake only
  --                       everything after is passed to the r2dfly migration script, e.g.
                           -- --parallelism 8 --writer-concurrency 8
EOF
}

DATASET="" KEYS="" NIFI_CONTAINER="r2dfly-bench-nifi" SHAKE_SCAN="false" RUN_SHAKE="true" RUN_R2DFLY="true"
R2DFLY_ARGS=()
while [[ $# -gt 0 ]]; do
  case "$1" in
    --dataset) DATASET="$2"; shift 2 ;;
    --keys) KEYS="$2"; shift 2 ;;
    --nifi-container) NIFI_CONTAINER="$2"; shift 2 ;;
    --shake-scan) SHAKE_SCAN="true"; shift ;;
    --skip-redisshake) RUN_SHAKE="false"; shift ;;
    --skip-r2dfly) RUN_R2DFLY="false"; shift ;;
    --) shift; R2DFLY_ARGS=("$@"); break ;;
    -h|--help) usage; exit 0 ;;
    *) echo "unknown argument: $1" >&2; usage; exit 1 ;;
  esac
done
case "$DATASET" in
  strings) KEYS="${KEYS:-10000000}" ;;
  hashes) KEYS="${KEYS:-1000000}" ;;
  lists) KEYS="${KEYS:-10000}" ;;
  live) KEYS="${KEYS:-100000}" ;;
  *) echo "error: --dataset must be strings, hashes, lists or live" >&2; usage; exit 1 ;;
esac

NET=r2dfly-bench-net SRC=r2dfly-bench-source TGT=r2dfly-bench-target
SHAKE_IMAGE=ghcr.io/tair-opensource/redisshake:latest
LOG_DIR="$PROJECT_ROOT/logs"
mkdir -p "$LOG_DIR"

cleanup() {
  podman rm -f "$SRC" "$TGT" r2dfly-bench-shake >/dev/null 2>&1 || true
}
trap cleanup EXIT

cli() { podman exec -i "$1" redis-cli "${@:2}"; }
now() { python3 -c 'import time; print(time.time())'; }

# populate - the dataset, generated by the source itself (Lua in 10k-key chunks), so seeding
# takes seconds rather than the hours a client loop would.
populate() {
  case "$DATASET" in
    strings|live) cli "$SRC" DEBUG POPULATE "$KEYS" key 64 >/dev/null ;;
    hashes|lists)
      local script
      if [[ "$DATASET" == "hashes" ]]; then
        script="local v=string.rep('x',32) for i=ARGV[1],ARGV[2] do local f={} for j=1,20 do f[#f+1]='f'..j f[#f+1]=v end redis.call('HSET','hash:'..i,unpack(f)) end return 0"
      else
        script="local v=string.rep('x',100) for i=ARGV[1],ARGV[2] do local e={} for j=1,1000 do e[j]=v end redis.call('RPUSH','list:'..i,unpack(e)) end return 0"
      fi
      local start=1 step=10000
      [[ "$DATASET" == "lists" ]] && step=100
      while [[ $start -le $KEYS ]]; do
        cli "$SRC" EVAL "$script" 0 "$start" "$(( start + step - 1 > KEYS ? KEYS : start + step - 1 ))" >/dev/null
        start=$(( start + step ))
      done ;;
  esac
  echo "  source holds $(cli "$SRC" DBSIZE) keys, $(cli "$SRC" INFO memory | sed -n 's/^used_memory_human://p' | tr -d '\r')"
}

# time_until_copied <label> [migration-pid] - from the target's first key until it holds as many
# as the source; fails if the migration exits first.
time_until_copied() {
  local want start="" n t
  want="$(cli "$SRC" DBSIZE)"
  while true; do
    if [[ -n "${2:-}" ]] && ! kill -0 "$2" 2>/dev/null && [[ "$(cli "$TGT" DBSIZE)" -lt "$want" ]]; then
      wait "$2" || true
      echo "  $1: the migration exited before the target held every key" >&2
      return 1
    fi
    n="$(cli "$TGT" DBSIZE 2>/dev/null || echo 0)"; t="$(now)"
    [[ -z "$start" && "$n" -gt 0 ]] && start="$t"
    [[ -n "$start" && "$n" -ge "$want" ]] && break
    sleep 0.5
  done
  python3 -c "e=$t-$start; print(f'  {\"$1\":<28} {$want:>10,} keys in {e:7.1f} s = {$want/e:>9,.0f} keys/s')"
}

# converged - every source key is on the target with the same value, checked by key count and a
# 2000-key random sample (strings and counters by GET, hashes by HGETALL, lists by LRANGE).
converged() {
  [[ "$(cli "$SRC" DBSIZE)" == "$(cli "$TGT" DBSIZE)" ]] || return 1
  local keys
  keys="$(for _ in $(seq 1 2000); do echo RANDOMKEY; done | cli "$SRC")"
  SAMPLE="$keys" python3 - "$SRC" "$TGT" <<'EOF'
import os, subprocess, sys
keys = [k for k in os.environ['SAMPLE'].split('\n') if k]
def values(container):
    types = subprocess.run(['podman', 'exec', '-i', container, 'redis-cli'], input=''.join(f'TYPE {k}\n' for k in keys),
                           capture_output=True, text=True).stdout.split('\n')
    cmd = {'string': 'GET {}', 'hash': 'HGETALL {}', 'list': 'LRANGE {} 0 -1'}
    script = ''.join(cmd.get(t, 'TYPE {}').format(k) + '\n' for k, t in zip(keys, types))
    return subprocess.run(['podman', 'exec', '-i', container, 'redis-cli', '--no-raw'], input=script, capture_output=True, text=True).stdout
sys.exit(0 if values(sys.argv[1]) == values(sys.argv[2]) else 1)
EOF
}

fresh_containers() {
  cleanup
  podman network create "$NET" >/dev/null 2>&1 || true
  podman run -d --name "$SRC" --network "$NET" docker.io/library/redis:7.4 --save "" --appendonly no --enable-debug-command yes >/dev/null
  podman run -d --name "$TGT" --network "$NET" docker.dragonflydb.io/dragonflydb/dragonfly:latest >/dev/null
  until cli "$SRC" PING >/dev/null 2>&1 && cli "$TGT" PING >/dev/null 2>&1; do sleep 0.5; done
}

# live_writes - 60 s of SET, INCR, HSET and LPUSH, each on its own random key of a 1M-key space.
live_writes() {
  podman run --rm --network "$NET" docker.io/library/redis:7.4 sh -c "
    for c in 'SET key:__rand_int__ v' 'INCR counter:__rand_int__' 'HSET hash:__rand_int__ f v' 'LPUSH list:__rand_int__ v'; do
      redis-benchmark -h $SRC -r 1000000 -n 100000000 -c 5 -P 16 -q \$c >/dev/null 2>&1 &
      pids=\"\$pids \$!\"
    done
    sleep 60; kill \$pids" || true
}

# time_until_converged <label> - after the live writes stop, until the target matches; gives up
# after 30 minutes and leaves the containers for a look.
time_until_converged() {
  local start t waited=0
  start="$(now)"
  until converged; do
    sleep 1
    waited=$(( waited + 1 ))
    if (( waited % 60 == 0 )); then
      echo "    $1: ${waited} s, source $(cli "$SRC" DBSIZE) keys, target $(cli "$TGT" DBSIZE) keys"
    fi
    if (( waited >= 1800 )); then
      echo "  $1: did not match the source within 30 minutes; $SRC and $TGT are left running" >&2
      trap - EXIT
      return 1
    fi
  done
  t="$(now)"
  python3 -c "print(f'  {\"$1\":<28} matched the source {$t-$start:6.1f} s after 60 s of writes stopped ({int(\"$(cli "$SRC" DBSIZE)\"):,} keys)')"
}

run_shake() {
  local mode="$1" label
  label="$(tr '[:upper:]' '[:lower:]' <<< "$mode")_reader"
  cli "$TGT" FLUSHALL >/dev/null
  podman run -d --rm --name r2dfly-bench-shake --network "$NET" -e "$mode=true" \
    -e SHAKE_SRC_ADDRESS="$SRC:6379" -e SHAKE_DST_ADDRESS="$TGT:6379" "$SHAKE_IMAGE" >/dev/null
  if [[ "$DATASET" == "live" ]]; then
    time_until_copied "RedisShake $label (initial)"
    live_writes
    time_until_converged "RedisShake $label"
  else
    time_until_copied "RedisShake $label"
  fi
  podman rm -f r2dfly-bench-shake >/dev/null
}

run_r2dfly() {
  cli "$TGT" FLUSHALL >/dev/null
  # NiFi joins the scratch network as soon as the migration script has created it.
  ( until podman inspect "$NIFI_CONTAINER" --format '{{json .NetworkSettings.Networks}}' 2>/dev/null | grep -q "\"$NET\"" \
        || podman network connect "$NET" "$NIFI_CONTAINER" >/dev/null 2>&1; do sleep 2; done ) &
  local joiner=$! log="$LOG_DIR/benchmark-r2dfly-$DATASET-$(date +%s).log" script=simple-migration.sh extra=()
  [[ "$DATASET" == "live" ]] && script=continuous-migration.sh extra=(--live-source replication)
  ( NIFI_CONTAINER_NAME="$NIFI_CONTAINER" "$PROJECT_ROOT/scripts/$script" --nifi-container "$NIFI_CONTAINER" \
      --source-connection-string "redis://$SRC:6379" --target-connection-string "redis://$TGT:6379" \
      --defaults -y ${extra+"${extra[@]}"} ${R2DFLY_ARGS+"${R2DFLY_ARGS[@]}"} > "$log" 2>&1 ) &
  local migration=$!
  if [[ "$DATASET" == "live" ]]; then
    time_until_copied "r2dfly (initial)" "$migration" || { echo "  see $log" >&2; return 1; }
    wait "$migration" || { echo "  r2dfly: $script failed, see $log" >&2; return 1; }
    live_writes
    time_until_converged "r2dfly replication"
    local creds
    creds="$(podman logs "$NIFI_CONTAINER" 2>&1 | grep -A1 'Generated Username' | tail -2)"
    NIFI_USER="$(sed -n '1s/.*\[\(.*\)\]/\1/p' <<< "$creds")" NIFI_PASS="$(sed -n '2s/.*\[\(.*\)\]/\1/p' <<< "$creds")" \
      "$PROJECT_ROOT/scripts/stop-continuous-migration.sh" --nifi-container "$NIFI_CONTAINER" >/dev/null 2>&1 || true
  else
    time_until_copied "r2dfly ${R2DFLY_ARGS[*]:-defaults}" "$migration" || { echo "  see $log" >&2; return 1; }
    wait "$migration" || { echo "  r2dfly: $script failed, see $log" >&2; return 1; }
  fi
  kill "$joiner" 2>/dev/null || true
}

echo "==> $DATASET, $KEYS keys, on $(podman info --format '{{.Host.CPUs}} CPUs, {{.Host.MemTotal}} bytes of memory' 2>/dev/null || echo 'this host')"
fresh_containers
populate
if [[ "$RUN_SHAKE" == "true" ]]; then
  run_shake SYNC
  [[ "$SHAKE_SCAN" == "true" && "$DATASET" != "live" ]] && run_shake SCAN
fi
if [[ "$RUN_SHAKE" == "true" && "$DATASET" == "live" && "$RUN_R2DFLY" == "true" ]]; then
  # The live writes changed the source; r2dfly starts from the same initial dataset.
  fresh_containers
  populate
fi
[[ "$RUN_R2DFLY" == "true" ]] && run_r2dfly
exit 0
